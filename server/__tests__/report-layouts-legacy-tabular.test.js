/* ============================================================
   server/utils/report-layouts.js — legacy_tabular renderer

   legacy_tabular is the platform built-in, always-resolvable fallback
   (report-card-templates.js's resolveTemplate) — any school that has
   never explicitly assigned a template default lands here, not just
   pre-engine snapshots. It was frozen when RCE1's remark/observation
   toggles shipped for the two newer layouts (subject_paired, marks_
   then_comments) and never got the same treatment — reported directly:
   turning off Principal's Comment still left its label and an empty
   box on the page, and Observation Ratings never appeared at all
   regardless of the toggle. Covers those fixes, plus the separate
   subject-name-not-id bug (also reported directly: "just seeing their
   ids") and the stray "Generated by Msingi..." cover line removed per
   an explicit request (redundant with the school's own customisable
   footerNote + date already in the real footer).

   Builds real IR via report-cards.js's _computeReportSections, same
   integration point report-layouts-subject-paired.test.js uses.
   ============================================================ */
'use strict';

jest.mock('../middleware/auth', () => ({ authMiddleware: (_r, _s, n) => n() }));
