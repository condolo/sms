describe('legacy_tabular.renderHtml — principal signature & school stamp (reported: "the stamp and principal\'s signature didn\'t show")', () => {
  test('neither image appears when the school has uploaded neither', () => {
    const html = LAYOUTS.legacy_tabular.renderHtml(computeSections());
    expect(html).not.toContain('<img');
  });

  test('a published snapshot\'s own frozen URLs render as <img> tags', () => {
    const html = LAYOUTS.legacy_tabular.renderHtml(
      computeSections({ principalSignatureUrl: 'data:image/png;base64,AAAA', schoolStampUrl: 'data:image/png;base64,BBBB' })
    );
    expect(html).toContain('<img src="data:image/png;base64,AAAA"');
    expect(html).toContain('<img src="data:image/png;base64,BBBB"');
  });

  test('falls back to the live school profile when the snapshot has none of its own (unpublished draft preview)', () => {
    const html = LAYOUTS.legacy_tabular.renderHtml(
      computeSections({}, {}, { school: { principalSignatureUrl: 'data:image/png;base64,CCCC', schoolStampUrl: 'data:image/png;base64,DDDD' } })
    );
    expect(html).toContain('<img src="data:image/png;base64,CCCC"');
    expect(html).toContain('<img src="data:image/png;base64,DDDD"');
  });

  test('the snapshot\'s own frozen URL wins over a later live school-profile change', () => {
    const html = LAYOUTS.legacy_tabular.renderHtml(
      computeSections(
        { principalSignatureUrl: 'data:image/png;base64,FROZEN' },
        {},
        { school: { principalSignatureUrl: 'data:image/png;base64,CHANGED_SINCE' } },
      )
    );
    expect(html).toContain('<img src="data:image/png;base64,FROZEN"');
    expect(html).not.toContain('CHANGED_SINCE');
  });

  test('turning off Principal\'s Comment removes the signature image too — it has nowhere left to sit', () => {
    const html = LAYOUTS.legacy_tabular.renderHtml(
      computeSections({ principalSignatureUrl: 'data:image/png;base64,AAAA', schoolStampUrl: 'data:image/png;base64,BBBB' }, { showPrincipalRemark: false })
    );
    expect(html).not.toContain('<img');
  });

  test('same fix applies to the PDF path', () => {
    const { spy, calls } = makeSpyDoc();
    const sections = computeSections();
    LAYOUTS.legacy_tabular.renderPdf(spy, sections, { principalSignature: Buffer.from('x'), schoolStamp: Buffer.from('y') }, true);
    expect(calls.some(c => c.method === 'image')).toBe(true);
  });
});
